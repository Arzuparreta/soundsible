"""Declared installed dependency footprint; external weights reported separately.

Run in each isolated interpreter. Uses package RECORD files, without caches,
generated bytecode, the interpreter itself, or a claim of minimal deployment.
"""
from __future__ import annotations

import argparse
import importlib.metadata as metadata
import json
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name


def closure(roots):
    pending = [(name, frozenset()) for name in roots]
    visited = set()
    packages = {}
    files = set()
    missing = set()
    while pending:
        name, extras = pending.pop()
        name = canonicalize_name(name)
        if (name, extras) in visited:
            continue
        visited.add((name, extras))
        try:
            distribution = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            missing.add(name)
            continue
        packages[name] = distribution.version
        for relative in distribution.files or []:
            path = Path(distribution.locate_file(relative))
            if path.is_file() and path.suffix != '.pyc':
                files.add(path.resolve())
        for text in distribution.requires or []:
            requirement = Requirement(text)
            if requirement.marker is None or any(requirement.marker.evaluate({'extra': extra}) for extra in extras or {''}):
                pending.append((requirement.name, frozenset(requirement.extras)))
    return dict(roots=roots, packages=packages, missing_declared_dependencies=sorted(missing),
                registered_installed_bytes=sum(path.stat().st_size for path in files),
                registered_files=len(files))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('output', type=Path)
    parser.add_argument('roots', nargs='+')
    args = parser.parse_args()
    value = closure(args.roots)
    args.output.write_text(json.dumps(value, indent=2)+'\n')
