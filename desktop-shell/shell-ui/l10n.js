export function detectLocale(languages = navigator.languages ?? [navigator.language]) {
  for (const language of languages) {
    const code = String(language).toLowerCase().split('-')[0];
    if (code in dictionaries) return code;
  }
  return 'en';
}

let currentLocale = detectLocale();

export function locale() {
  return currentLocale;
}

export function setLocale(value) {
  currentLocale = value in dictionaries ? value : 'en';
  document.documentElement.lang = currentLocale;
}

export function t(key, params = {}) {
  const template = dictionaries[currentLocale]?.[key] ?? dictionaries.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => (
    params[name] === undefined ? `{${name}}` : String(params[name])
  ));
}

export function applyStaticTranslations(root = document) {
  setLocale(detectLocale());
  root.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  document.title = t('title');
}
